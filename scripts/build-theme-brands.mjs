/**
 * Generates lib/theme-brands.ts: the brands ThemeScope's `brand` prop
 * accepts, one per `<brand>-scoped.css` in styles/brands/. A brand without a
 * scoped file can't be scoped to part of a page, so it isn't offered.
 *
 * Called from sd.config.mjs right after the scoped CSS is written, so the
 * type and the files can't disagree. Before 1.3.2 the type was written by
 * hand in lib/theme-scope.tsx (decisions/0021's Consequences).
 */

import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export function scopedBrands(files) {
  return files
    .map(f => f.match(/^([a-z0-9-]+)-scoped\.css$/)?.[1])
    .filter(Boolean)
    .sort()
}

export function themeBrandsSource(brands) {
  if (brands.length === 0) {
    throw new Error('No *-scoped.css in styles/brands/. ThemeScope needs at least one scoped brand file.')
  }
  return [
    '// Generated by scripts/build-theme-brands.mjs from the *-scoped.css files in',
    '// styles/brands/. Do not edit: run `npm run tokens`.',
    '',
    '/** The brands a ThemeScope can apply to part of a page: one per scoped brand file. */',
    // Written as a literal union, not `(typeof THEME_BRANDS)[number]`: the doc
    // twin generator only expands a plain union, and agents read the twin.
    `export type ThemeBrand = ${brands.map(b => `'${b}'`).join(' | ')}`,
    '',
    `export const THEME_BRANDS: readonly ThemeBrand[] = [${brands.map(b => `'${b}'`).join(', ')}]`,
    '',
  ].join('\n')
}

export function buildThemeBrands() {
  const brands = scopedBrands(readdirSync('styles/brands'))
  writeFileSync('lib/theme-brands.ts', themeBrandsSource(brands))
  console.log(`✓ Built lib/theme-brands.ts (${brands.join(', ')})`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) buildThemeBrands()
