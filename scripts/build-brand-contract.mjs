/**
 * Builds docs/brand-contract.md: every token a project brand may set, with
 * its base values, generated from the "amezquita.brand": "settable" markers
 * (decisions/0028). Reads tokens/token-reference.json, so it runs after
 * buildTokenReference in sd.config.mjs.
 *
 * Generated; never hand-edit the output. Change a marker and run npm run tokens.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { MODE_PREFIXES, loadSystem } from '../brand/contract.mjs'

const FAMILIES = [
  ['Colour', name => name.startsWith('color-')],
  ['Type', name => /^(font|line-height|letter-spacing)-/.test(name)],
  ['Shape', name => /^border-(radius|width)-/.test(name)],
  ['Elevation', name => name.startsWith('shadow-')],
  ['Component', () => true],
]

const cell = value => (value === null || value === undefined || value === '' ? '—' : `\`${String(value).replace(/\|/g, '\\|')}\``)
const text = value => (value ? value.replace(/\|/g, '\\|').replace(/\n/g, ' ') : '')

export function renderBrandContract(system, reference) {
  const byName = new Map(reference.tokens.map(t => [t.name, t]))
  const lines = [
    '# Brand contract',
    '',
    '> Generated by `npm run tokens` from the `"amezquita.brand": "settable"` markers in `tokens/`. Do not edit. Why it exists: [`decisions/0028`](../decisions/0028-brand-contract-for-project-brands.md).',
    '',
    `A project brand may set the ${system.settable.size} tokens below, and tokens of its own named \`<brand>-*\`. Anything else is the system's own. Check a brand, and build its CSS:`,
    '',
    '```sh',
    'npx amezquita-brand check <brand-folder> [--pairs <file>]',
    'npx amezquita-brand build <brand-folder> --out <dir> [--pairs <file>]',
    '```',
    '',
    '`build` checks first and builds nothing from a brand that fails. It writes `<brand>-light.css`, `<brand>-dark.css` and `<brand>-scoped.css`, the same three files a brand in this package gets, and `<brand>-fonts.json`, the Google Fonts link for the fonts the brand names. Load the package\'s `base-light.css` and `base-dark.css` first, then the brand\'s light and dark files, or only its scoped file for `<ThemeScope brand="<brand>">`. It needs `style-dictionary` ^5 installed in the project, an optional peer dependency.',
    '',
    '## The brand folder',
    '',
    '- `tokens.json` for light and, if the brand changes anything in dark mode, `dark.json`. Flat token names as keys, DTCG `$value` and `$type`: `"color-neutral-50": { "$value": "#f7f4ee", "$type": "color" }`.',
    '- A value is hex, another value of the token\'s type, a reference to a semantic or component token (`{color-accent-default}`), or a reference to a primitive in `tokens/global.json` (`{color.warm-500}`). Write colours as hex: the contrast check skips anything else.',
    '',
    '## What the check enforces',
    '',
    '- **Only settable tokens.** Every name is in the tables below or starts with `<brand>-`. A misspelt name fails, with the nearest real name.',
    '- **The right type.** `$type` matches the system\'s, and every reference resolves to a value, not back to itself.',
    '- **Colours are hex.** `#rrggbb`, or `#rrggbbaa` with transparency (`#0000` for transparent), so the contrast check can read every one.',
    `- **Dark files set lighting only:** names starting with ${MODE_PREFIXES.map(p => `\`${p}\``).join(', ')}, or the brand's own.`,
    '- **No light value leaks into dark mode.** A literal or primitive set in `tokens.json`, for a token base gives different values in light and dark, has to be set in `dark.json` too. A reference to a semantic token follows the mode by itself.',
    '- **Heading sizes and line-heights travel together.** Setting `font-size-hN` means setting `line-height-hN`, on the 4px grid.',
    `- **Contrast.** The ${system.pairs.length} pairs in \`tokens/contrast-pairs.json\`, in light and dark, plus any \`--pairs\` file for the brand's own tokens.`,
    '',
  ]

  const remaining = new Set(system.settable.keys())
  for (const [family, match] of FAMILIES) {
    const names = [...remaining].filter(match)
    if (names.length === 0) continue
    for (const n of names) remaining.delete(n)
    lines.push(`## ${family}`, '', '| Token | Type | Base light | Base dark | Description |', '|---|---|---|---|---|')
    for (const name of names) {
      const def = system.settable.get(name)
      const entry = byName.get(name)
      lines.push(`| \`${name}\` | ${def.type ?? '—'} | ${cell(entry?.resolved?.['base-light'] ?? entry?.rawValue)} | ${cell(entry?.resolved?.['base-dark'] ?? entry?.rawValue)} | ${text(def.description)} |`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

export function buildBrandContract() {
  const system = loadSystem()
  const reference = JSON.parse(readFileSync('tokens/token-reference.json', 'utf8'))
  writeFileSync('docs/brand-contract.md', renderBrandContract(system, reference))
  console.log(`✓ Built docs/brand-contract.md (${system.settable.size} settable tokens)`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildBrandContract()
}
