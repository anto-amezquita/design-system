import StyleDictionary from 'style-dictionary';
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { makeResolver } from './lib/resolve-token.mjs';

// Token axis contract — enforced at build time.
// Mode axis owns lighting: background, text, border, feedback.
// Expression axis owns personality: accent, border-radius.
// Keeping them separate means both can be active simultaneously with no cascade conflict.
const TOKEN_CONTRACTS = {
  mode: [
    'color-surface-',
    'color-curtain',
    'color-text-',
    'color-border-',
    'color-feedback-',
    'color-neutral-',
    'color-accent-',
    'button-secondary-',
    'checkbox-',
    'radio-',
    'switch-',
    'textarea-',
  ],
  expression: [
    'color-accent-',
    'border-radius-',
    'button-border-radius',
    'card-border-radius',
    'input-border-radius',
    'select-border-radius',
  ],
};

function validateTokenContract(filePath, axis) {
  const allowed = TOKEN_CONTRACTS[axis];
  const tokens = JSON.parse(readFileSync(filePath, 'utf8'));
  const violations = Object.keys(tokens).filter(
    key => !allowed.some(prefix => key.startsWith(prefix))
  );
  if (violations.length > 0) {
    throw new Error(
      `[token contract] "${axis}" axis violation in ${filePath}.\n` +
      `These tokens are not allowed on this axis: ${violations.join(', ')}\n` +
      `Mode axis owns: surface, text, border, feedback.\n` +
      `Expression axis owns: accent, border-radius.`
    );
  }
}

// Patch size/rem to skip complex CSS functions (clamp, min, max, calc).
// SD5's built-in throws when parseFloat() hits a non-numeric value like clamp().
StyleDictionary.registerTransform({
  name: 'size/rem',
  type: 'value',
  filter: (token, options) => {
    const type = options?.usesDtcg ? token.$type : token.type;
    return type === 'dimension' || type === 'fontSize';
  },
  transform: (token, _, options) => {
    const raw = options?.usesDtcg ? token.$value : token.value;
    const str = String(raw ?? '');
    if (/^(clamp|min|max|calc|env|var)\(/.test(str)) return str;
    const unitMatch = str.match(/[a-zA-Z%]+$/);
    const unit = unitMatch?.[0];
    const num = parseFloat(str);
    if (isNaN(num)) return str;
    if (num === 0) return '0';
    return unit ? `${num}${unit}` : `${num}rem`;
  },
});

StyleDictionary.registerFormat({
  name: 'css/brand-variables',
  format: ({ dictionary, options }) => {
    const { brand, selector: selectorOverride, colorScheme } = options;
    const selector = selectorOverride ?? (brand === 'portfolio' ? ':root' : `[data-brand="${brand}"]`);
    const extra = colorScheme ? `  color-scheme: ${colorScheme};\n` : '';
    const vars = dictionary.allTokens
      .map(token => {
        // preserveSemanticRefs: emit `var(--ref)` instead of the resolved value when
        // the token references another semantic token (kebab ref, no dot). Used by the
        // bold build so mode-owned indirection tokens (e.g. color-accent-bold, flipped
        // by dark.css) resolve per-mode in the cascade instead of being baked in.
        const original = options.usesDtcg ? token.original?.$value : token.original?.value;
        if (options.preserveSemanticRefs && typeof original === 'string') {
          const ref = original.match(/^\{([a-z0-9-]+)\}$/);
          if (ref && !ref[1].includes('.')) return `  --${token.name}: var(--${ref[1]});`;
        }
        return `  --${token.name}: ${options.usesDtcg ? token.$value : token.value};`;
      })
      .join('\n');
    return `/* Auto-generated by Style Dictionary — do not edit directly */\n/* Brand: ${brand} */\n\n${selector} {\n${extra}${vars}\n}\n`;
  }
});

const portfolio = new StyleDictionary({
  usesDtcg: true,
  source: [
    'tokens/global.json',
    'tokens/components/*.json',
    'tokens/brands/portfolio/tokens.json',
  ],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: '',
      buildPath: 'styles/brands/',
      files: [{
        destination: 'portfolio.css',
        format: 'css/brand-variables',
        options: {
          brand: 'portfolio',
          // Also targets [data-mode="light"] and [data-expression="default"] so demo panels
          // can explicitly opt into the light/default state even when the site is in dark/bold.
          selector: ':root, [data-mode="light"], [data-expression="default"]',
          // Late-bind semantic references: component tokens like
          // accordion-trigger-color: {color-text-primary} emit as var(--color-text-primary)
          // so they resolve against the active mode/expression scope. Without this they
          // bake in light values and every component token needs a hand-written dark
          // override.
          preserveSemanticRefs: true,
        }
      }]
    }
  }
});

