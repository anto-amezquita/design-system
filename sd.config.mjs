// Reads and JSON.parses a token file, throwing a message that names the
// file — without this, a malformed tokens/components/*.json surfaces as a
// bare "Unexpected token" with no indication of which file it came from.
function loadTokenJson(path) {
  let raw
  try {
    raw = readFileSync(path, 'utf8')
  } catch (err) {
    throw new Error(`[computeChangedTokens] Could not read ${path}: ${err.message}`)
  }
  try {
    return JSON.parse(raw)
  } catch (err) {
    throw new Error(`[computeChangedTokens] ${path} is not valid JSON: ${err.message}`)
  }
}

// Loaded once and shared by both computeChangedTokens calls below — dark and
// bold otherwise each independently re-read and re-parsed the same set of
// files (tokens/global.json, tokens/brands/portfolio/tokens.json, every file
// in tokens/components/) for identical results.
const globalJsonForDiff = loadTokenJson('tokens/global.json')
const baseJsonForDiff = loadTokenJson('tokens/brands/portfolio/tokens.json')
const componentJsonForDiff = Object.assign(
  {},
  ...readdirSync('tokens/components')
    .filter(f => f.endsWith('.json'))
    .map(f => loadTokenJson(`tokens/components/${f}`))
)
const lightMapForDiff = { ...componentJsonForDiff, ...baseJsonForDiff }

// Axis diff sets — every token whose *resolved* value changes under an axis
// override must be re-declared inside that axis's scope. var() references in
// custom properties substitute on the element where the property is declared,
// so a component token declared on :root bakes in light values for any nested
// [data-mode="dark"] scope (story wrappers, /design-system demo panels) even
// when its value is var(--color-text-primary). Re-declaring the changed token
// on the axis selector makes substitution happen against that scope's cascade.
function computeChangedTokens(overridesPath) {
  const overrides = loadTokenJson(overridesPath)
  const resolveLight = makeResolver(lightMapForDiff, globalJsonForDiff)
  const resolveAxis = makeResolver({ ...lightMapForDiff, ...overrides }, globalJsonForDiff)

  const changed = new Set()
  for (const name of Object.keys(lightMapForDiff)) {
    if (name in overrides) continue // isSource already emits these

    // Composite/object-valued tokens (a future DTCG shadow or typography
    // token) resolve to null from makeResolver, which can't diff them — so
    // rather than silently treat "can't tell" as "unchanged" (which would
    // reintroduce the exact light-value-baked-into-dark-scope bug this
    // function exists to fix, for that token), always re-declare them.
    const rawValue = lightMapForDiff[name].$value ?? lightMapForDiff[name].value
    if (rawValue && typeof rawValue === 'object') {
      changed.add(name)
      continue
    }

    const light = resolveLight(name)
    const axis = resolveAxis(name)
    if (light !== null && axis !== null && light !== axis) changed.add(name)
  }
  return changed
}

const darkChanged = computeChangedTokens('tokens/brands/dark/tokens.json')
const boldChanged = computeChangedTokens('tokens/brands/bold/tokens.json')

const dark = new StyleDictionary({
  usesDtcg: true,
  // Base tokens in `include` so SD understands dark/tokens.json intentionally overrides them.
  // Collision warnings only fire for source-vs-source conflicts; include-vs-source is expected.
  include: [
    'tokens/global.json',
    'tokens/components/*.json',
    'tokens/brands/portfolio/tokens.json',
  ],
  source: [
    'tokens/brands/dark/tokens.json',
  ],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: '',
      buildPath: 'styles/brands/',
      files: [{
        destination: 'dark.css',
        format: 'css/brand-variables',
        filter: (token) => token.isSource || darkChanged.has(token.name),
        // preserveSemanticRefs keeps re-declared component tokens as var() refs
        // so the dark+bold combination still composes (bold's accent overrides
        // win inside a scope carrying both attributes).
        options: { brand: 'dark', selector: '[data-mode="dark"]', colorScheme: 'dark', preserveSemanticRefs: true }
      }]
    }
  }
});

await dark.buildAllPlatforms();
console.log('✓ Built dark.css');

